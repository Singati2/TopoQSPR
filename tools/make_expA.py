"""Experiment A (cohort sensitivity) table and figure from `run_experiment.py exp-a` outputs.

Usage: python tools/make_expA.py OUT_DIR RUN_DIR [RUN_DIR ...]

Each RUN_DIR holds summary.json (counts, jaccard, controlled_in_naive_share, mesh_ids).
Writes tab_expA.tex and fig_expA.pdf/.png. Nothing is typed by hand.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

SERIES = "#2a78d6"   # reference palette slot 1 (validated)
INK, INK_2, GRID = "#0b0b0b", "#52514e", "#d9d8d4"
NAME = {"D003924": "Type 2 diabetes", "D006973": "Hypertension", "D001249": "Asthma",
        "D001943": "Breast neoplasms", "D008881": "Migraine (pilot)"}

plt.rcParams.update({"font.size": 8, "axes.edgecolor": INK_2, "axes.labelcolor": INK, "xtick.color": INK_2,
                     "ytick.color": INK_2, "axes.spines.top": False, "axes.spines.right": False,
                     "figure.dpi": 150, "savefig.bbox": "tight"})


def _argv_value(argv: list, flag: str) -> str:
    return argv[argv.index(flag) + 1] if flag in argv and argv.index(flag) + 1 < len(argv) else ""


def load(run: Path) -> dict:
    s = json.loads((run / "summary.json").read_text())
    info = json.loads((run / "run_info.json").read_text()) if (run / "run_info.json").exists() else {}
    mesh = s["mesh_ids"]["controlled"][0]
    c, n = s["counts"]["controlled"], s["counts"]["naive"]
    return dict(mesh=mesh, name=NAME.get(mesh, mesh),
                naive_text=_argv_value(info.get("argv") or [], "--naive-text"),
                naive_headings=len(s["mesh_ids"]["naive"]),
                naive_rows=n["manifest_included"], naive_parents=n["distinct_parent_chembl_ids"],
                naive_ok=n["standardised_ok"], controlled=c["standardised_ok"],
                jaccard_key=s["jaccard"]["standardised_parent_inchikey"],
                jaccard_struct=s["jaccard"]["structures_used"],
                share=s["controlled_in_naive_share"])


def table(rows: list[dict], out: Path) -> None:
    body = "\n".join(
        f"{r['name']} & {r['naive_headings']} & {r['naive_rows']} & {r['naive_ok']} & {r['controlled']} & "
        f"{r['jaccard_key']:.2f} & {r['jaccard_struct']:.2f} & {100 * r['share']:.0f}\\% \\\\" for r in rows)
    tex = r"""\begin{table}[t]
\centering\footnotesize
\caption{Experiment A, cohort sensitivity (ChEMBL~37). Naive: the v0.x substring query on MeSH headings, all phases, salts kept; controlled: the confirmed heading, phase~4 for the indication, parent structures, standardised and de-duplicated. Jaccard overlaps are on standardised parent InChIKeys and on the structures each pipeline would hand to the descriptor stage. The last column is the share of controlled drugs that also appear in the naive set. Generated by \texttt{tools/make\_expA.py}.}
\label{tab:expA}
\resizebox{\linewidth}{!}{%%
\begin{tabular}{lrrrrrrr}
\toprule
Disease & Headings matched & Naive rows & Naive drugs & Controlled drugs & Jaccard (parents) & Jaccard (structures) & Controlled $\subseteq$ naive \\
\midrule
%s
\bottomrule
\end{tabular}}
\end{table}
""" % body
    (out / "tab_expA.tex").write_text(tex)


def figure(rows: list[dict], out: Path) -> None:
    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(6.4, 0.5 * len(rows) + 1.2), gridspec_kw=dict(wspace=0.55))
    ys = list(range(len(rows)))[::-1]
    for y, r in zip(ys, rows):
        ax1.plot([r["controlled"], r["naive_ok"]], [y, y], color=GRID, lw=1.5, zorder=1)
        ax1.scatter([r["naive_ok"]], [y], s=34, color="white", edgecolors=SERIES, linewidths=1.5, zorder=3)
        ax1.scatter([r["controlled"]], [y], s=34, color=SERIES, zorder=3)
        ax1.text(r["naive_ok"], y + 0.3, f"{r['naive_ok']}", ha="center", fontsize=6.5, color=INK)
        ax1.text(r["controlled"], y + 0.3, f"{r['controlled']}", ha="center", fontsize=6.5, color=INK)
        ax2.barh(y, r["jaccard_key"], color=SERIES, height=0.55)
        ax2.text(r["jaccard_key"] + 0.01, y, f"{r['jaccard_key']:.2f}", va="center", fontsize=6.5, color=INK)
    ax1.set_yticks(ys, [r["name"] for r in rows])
    ax1.set_xlabel("drugs (filled: controlled; hollow: naive)")
    ax1.set_xlim(0, max(r["naive_ok"] for r in rows) * 1.15)
    ax1.grid(axis="x", color=GRID, lw=0.5)
    ax2.set_yticks(ys, ["" for _ in rows])
    ax2.set_xlim(0, 1)
    ax2.set_xlabel("Jaccard overlap (standardised parents)")
    ax2.grid(axis="x", color=GRID, lw=0.5)
    for ext in ("pdf", "png"):
        fig.savefig(out / f"fig_expA.{ext}")
    plt.close(fig)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    ap.add_argument("runs", nargs="+")
    a = ap.parse_args()
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    rows = sorted((load(Path(r)) for r in a.runs), key=lambda r: -r["naive_ok"])
    table(rows, out)
    figure(rows, out)
    (out / "expA_macros.tex").write_text(
        "\\newcommand{\\expAnDiseases}{%d}\n\\newcommand{\\expAminHeadings}{%d}\n"
        "\\newcommand{\\expAmaxHeadings}{%d}\n\\newcommand{\\expAminJ}{%.2f}\n\\newcommand{\\expAmaxJ}{%.2f}\n"
        "\\newcommand{\\expAminShare}{%.0f}\n\\newcommand{\\expAminRatio}{%.0f}\n\\newcommand{\\expAmaxRatio}{%.0f}\n"
        % (len(rows), min(r["naive_headings"] for r in rows), max(r["naive_headings"] for r in rows),
           min(r["jaccard_key"] for r in rows), max(r["jaccard_key"] for r in rows),
           100 * min(r["share"] for r in rows),
           min(r["naive_ok"] / r["controlled"] for r in rows), max(r["naive_ok"] / r["controlled"] for r in rows)))
    for r in rows:
        print(f"{r['name']:18s} naive {r['naive_ok']:4d}  controlled {r['controlled']:3d}  "
              f"J={r['jaccard_key']:.2f}  controlled-in-naive {100 * r['share']:.0f}%")


if __name__ == "__main__":
    main()
