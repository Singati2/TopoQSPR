"""Paper results: LaTeX tables and figures generated only from a run's result files.

Usage: python tools/make_results.py RESULTS_DIR OUT_DIR

Reads (written by `topoqspr run` with a protocol stage):
  confirmatory.csv        one row per (target x comparison) of the confirmatory family
  summary.csv             baseline ladder per target / feature set / learner
  run_record.json         provenance (commit, release, config hash, seeds)

Writes:
  tab_confirmatory.tex    the confirmatory table (ΔR², CI, BH/BY q, permutation p, bootstrap CI)
  tab_ladder.tex          pooled R² for every feature set x target (learner "selected")
  fig_confirmatory.pdf/png forest plot of ΔR²(TI − size) with corrected-t and bootstrap intervals
  provenance.tex          one macro per provenance fact (\\runCommit, \\chemblRelease, ...)
No value in these files is typed by hand; the paper \\input{}s them.
"""

