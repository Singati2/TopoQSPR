def _read(path: Path) -> pd.DataFrame:
    # "null" is a feature-set name, not a missing value
    return pd.read_csv(path, keep_default_na=False, na_values=[""])


def _f(x, nd=2, dash="--") -> str:
    try:
        v = float(x)
    except (TypeError, ValueError):
        return dash
    return dash if not math.isfinite(v) else f"{v:.{nd}f}"


def _p(x) -> str:
    try:
        v = float(x)
    except (TypeError, ValueError):
        return "--"
    if not math.isfinite(v):
        return "--"
    return "$<$0.001" if v < 0.001 else f"{v:.3f}"


def _flag(x) -> bool:
    return str(x).strip().lower() in ("true", "1")


def _tex(s: str) -> str:
    return str(s).replace("_", "\\_").replace("%", "\\%")


def confirmatory_table(conf: pd.DataFrame, out: Path) -> None:
    rows = []
    for _, r in conf.iterrows():
        in_fam = _flag(r.get("in_family", True))
        rows.append(" & ".join([
            TARGET.get(r["target"], _tex(r["target"])), _tex(r["comparison"]), _f(r["n"], 0),
            _f(r["d_r2_mean"], 3), f"[{_f(r['d_r2_ci_low'], 3)}, {_f(r['d_r2_ci_high'], 3)}]",
            _p(r["d_r2_p"]), _p(r["d_r2_q_bh"]) if in_fam else "excl.", _p(r["d_r2_q_by"]) if in_fam else "excl.",
            _f(r["d_mae_mean"], 3),
            ("yes" if _flag(r.get("informative_bh")) else "no") if in_fam else "excl.",
        ]) + " \\\\")
    fam_m = int(float(conf["family_m"].iloc[0])) if "family_m" in conf and len(conf) else len(conf)
    thr = float(conf["practical_threshold"].iloc[0]) if len(conf) else 0.05
    tex = r"""\begin{table}[t]
\centering\footnotesize
\caption{Confirmatory family (%d members): paired gain of the topological-index model over the size baseline, learner \texttt{selected}. $\Delta R^2$ and $\Delta$MAE (MAE$_{\mathrm{size}}-$MAE$_{\mathrm{TI}}$, in target units) are means over %s repeated outer folds with the corrected repeated $k$-fold $t$-test 95\%% CI and $p$; $q$: Benjamini--Hochberg and Benjamini--Yekutieli over the family. ``Informative'': $q_{\mathrm{BH}}\le0.05$ and $\Delta R^2>0$; practical threshold $\Delta R^2\ge%.2f$. The Y-randomisation and bootstrap controls are in Table~\ref{tab:controls}. Generated by \texttt{tools/make\_results.py}.}
\label{tab:confirmatory}
\resizebox{\linewidth}{!}{%%
\begin{tabular}{llrrlllllrl}
\toprule
Target & Comparison & $n$ & $\Delta R^2$ & 95\%% CI & $p$ & $q_{\mathrm{BH}}$ & $q_{\mathrm{BY}}$ & $\Delta$MAE & Informative \\
\midrule
%s
\bottomrule
\end{tabular}}
\end{table}
""" % (fam_m, "the", thr, "\n".join(rows))
    (out / "tab_confirmatory.tex").write_text(tex)


def _r2cell(v, nd=3) -> str:
    """Pooled R² for a table: values below -1 are printed as $<-1$ (the number itself is in the CSV)."""
    try:
        x = float(v)
    except (TypeError, ValueError):
        return "--"
    if not math.isfinite(x):
        return "--"
    return "$<$$-$1" if x < -1 else f"{x:.{nd}f}"


def ladder_table(summary: pd.DataFrame, ad: pd.DataFrame | None, learner: str, out: Path) -> dict:
    """Pooled R² (primary) and, from ad_summary.csv, the pre-specified secondary in-domain R²."""
    targets = list(dict.fromkeys(summary["target"]))
    sets = [s for s in LADDER if s in set(summary["set"])]
    head = " & ".join(["Feature set"] + [f"\\multicolumn{{2}}{{c}}{{{TARGET.get(t, _tex(t))}}}" for t in targets]) + " \\\\"
    sub = " & ".join([""] + ["all & in-dom."] * len(targets)) + " \\\\"
    lines, info = [], {}
    for s in sets:
        cells = []
        for t in targets:
            r = summary[(summary["target"] == t) & (summary["learner"] == learner) & (summary["set"] == s)]
            a = ad[(ad["target"] == t) & (ad["learner"] == learner) & (ad["set"] == s)] if ad is not None else pd.DataFrame()
            if r.empty:
                cells += ["--", "--"]
                continue
            pooled = float(r.iloc[0]["r2_pooled_mean"])
            indom = float(a.iloc[0]["r2_in_domain_pooled_mean"]) if len(a) and pd.notna(a.iloc[0]["r2_in_domain_pooled_mean"]) else math.nan
            info[(t, s)] = (pooled, indom)
            cells += [_r2cell(pooled) + ("$^{\\dagger}$" if _flag(r.iloc[0]["underpowered"]) else ""), _r2cell(indom)]
        lines.append(" & ".join([LABEL.get(s, _tex(s))] + cells) + " \\\\")
    ns = " & ".join(["$n$"] + [f"\\multicolumn{{2}}{{c}}{{{_f(summary[summary['target'] == t]['n'].iloc[0], 0)}}}" for t in targets]) + " \\\\"
    share = ""
    if ad is not None:
        sh = [ad[(ad["target"] == t) & (ad["learner"] == learner) & (ad["set"] == "TI")]["share_outside_pooled"] for t in targets]
        share = " & ".join(["outside domain"] + [f"\\multicolumn{{2}}{{c}}{{{100 * float(x.iloc[0]):.1f}\\%}}" if len(x) else "\\multicolumn{2}{c}{--}" for x in sh]) + " \\\\"
    tex = r"""\begin{table}[t]
\centering\footnotesize
\caption{Baseline ladder: pooled cross-validated $R^2$ of each feature set (learner \texttt{selected}, chosen inside each outer training fold; $5\times5$ repeated nested CV), on all molecules (primary) and on the molecules inside the kNN applicability domain fitted in each training fold (pre-specified secondary). A pooled $R^2$ below $-1$ marks a feature set on which the selected model extrapolated on out-of-domain molecules; the values are in \texttt{summary.csv}. ``Outside domain'': share of outer-test molecules outside the domain of the TI set. $^{\dagger}$underpowered. Generated by \texttt{tools/make\_results.py}.}
\label{tab:ladder}
\begin{tabular}{l%s}
\toprule
%s
%s
\midrule
%s
\midrule
%s
%s
\bottomrule
\end{tabular}
\end{table}
""" % ("rr" * len(targets), head, sub, "\n".join(lines), ns, share)
    (out / "tab_ladder.tex").write_text(tex)
    return info


def forest(conf: pd.DataFrame, out: Path) -> None:
    rows = list(conf.iterrows())
    fig, ax = plt.subplots(figsize=(4.8, 0.45 * max(len(rows), 2) + 1.1))
    ax.set_ylim(-0.6, len(rows) - 0.4)
    thr = float(conf["practical_threshold"].iloc[0]) if len(rows) else 0.05
    for i, (_, r) in enumerate(rows[::-1]):
        m, lo, hi = (float(r[k]) if pd.notna(r[k]) else math.nan for k in ("d_r2_mean", "d_r2_ci_low", "d_r2_ci_high"))
        blo, bhi = (float(r[k]) if ("boot_d_r2_ci_low" in r and pd.notna(r[k])) else math.nan
                    for k in ("boot_d_r2_ci_low", "boot_d_r2_ci_high"))
        hollow = _flag(r.get("underpowered")) or not _flag(r.get("in_family", True))
        if math.isfinite(lo) and math.isfinite(hi):
            ax.plot([lo, hi], [i + 0.12, i + 0.12], color=SERIES, lw=2, solid_capstyle="round", zorder=2)
        if math.isfinite(blo) and math.isfinite(bhi):
            ax.plot([blo, bhi], [i - 0.12, i - 0.12], color=INK_2, lw=1.2, solid_capstyle="round", zorder=2)
        if math.isfinite(m):
            ax.scatter([m], [i + 0.12], s=30, zorder=4, color="white" if hollow else SERIES,
                       edgecolors=SERIES, linewidths=1.5)
    ax.set_yticks(range(len(rows)), [f"{TARGET.get(r['target'], r['target']).replace('$', '')}: {r['comparison']}"
                                      for _, r in rows[::-1]])
    ax.axvline(0, color=INK_2, lw=0.8)
    ax.axvline(thr, color=INK_2, lw=0.8, ls=(0, (3, 3)))
    ax.text(thr, len(rows) - 0.45, f" {thr:+.2f} practical threshold", fontsize=6.5, color=INK_2, va="bottom")
    ax.set_xlabel("ΔR² of topological indices over the size baseline")
    ax.grid(axis="x", color=GRID, lw=0.5)
    fig.text(0, -0.08, "Blue: corrected repeated k-fold t 95 % CI (upper bar). Grey: whole-procedure\n"
             "paired bootstrap 95 % CI (lower bar). Hollow: underpowered or outside the family.",
             fontsize=6.5, color=INK_2, va="top")
    for ext in ("pdf", "png"):
        fig.savefig(out / f"fig_confirmatory.{ext}")
    plt.close(fig)


def _controls_rows(res: Path) -> list[dict]:
    """One row per (target, set) of a run's protocol stage: permutation summary + bootstrap percentile
    interval + how many resamples exploded (|ΔR²| > 1, the mark of extrapolation)."""
    rows = []
    if not (res / "permutation_summary.csv").exists():
        return rows
    ps = _read(res / "permutation_summary.csv")
    boot = _read(res / "bootstrap.csv") if (res / "bootstrap.csv").exists() else pd.DataFrame()
    conf = _read(res / "confirmatory.csv") if (res / "confirmatory.csv").exists() else pd.DataFrame()
    for _, r in ps.iterrows():
        row = dict(run=res.name, target=r["target"], learner=r["learner"], set=r["set"],
                   observed=float(r["observed_r2_pooled_mean"]), null_q95=float(r["null_q95"]),
                   perm_p=float(r["p"]), uninformative=_flag(r["uninformative"]),
                   boot_lo=math.nan, boot_hi=math.nan, boot_n=0, boot_exploded=0)
        if len(boot) and r["set"] != "size":
            b = boot[(boot["target"] == r["target"]) & (boot["set"] == r["set"]) & (boot["resample"].astype(float) >= 0)]
            d = b["d_r2"].astype(float)
            if len(d):
                row.update(boot_lo=float(d.quantile(0.025)), boot_hi=float(d.quantile(0.975)), boot_n=int(len(d)),
                           boot_exploded=int((d.abs() > 1).sum()), boot_median=float(d.median()))
        rows.append(row)
    return rows


def controls_table(res: Path, extra: list[Path], out: Path) -> list[dict]:
    rows = _controls_rows(res)
    for e in extra:
        rows += _controls_rows(e)
    lines = []
    for r in rows:
        boot = "--" if r["set"] == "size" or not r["boot_n"] else \
            f"[{_r2cell(r['boot_lo'], 2)}, {_f(r['boot_hi'], 2)}] ({r['boot_exploded']}/{r['boot_n']})"
        lines.append(" & ".join([TARGET.get(r["target"], _tex(r["target"])), _tex(r["learner"]), _tex(r["set"]),
                                 _r2cell(r["observed"]), _r2cell(r["null_q95"]), _p(r["perm_p"]),
                                 "yes" if r["uninformative"] else "no", boot]) + " \\\\")
    tex = r"""\begin{table}[t]
\centering\footnotesize
\caption{Pre-specified controls, run with a single control learner per the compute plan. Permutation: pooled $R^2$ of the control learner on the real targets against 200 Y-randomised targets (95th percentile of the null and permutation $p$); a set is ``uninformative'' if its real $R^2$ does not exceed the null's 95th percentile. Bootstrap: 2.5--97.5 percentile interval of $\Delta R^2$(set $-$ size) over 200 resamples of the whole nested procedure, and in parentheses the number of resamples in which $|\Delta R^2|>1$, i.e.\ the control learner extrapolated on out-of-domain molecules. Values below $-1$ are printed as $<-1$. Generated by \texttt{tools/make\_results.py}.}
\label{tab:controls}
\resizebox{\linewidth}{!}{%%
\begin{tabular}{llllllll}
\toprule
Target & Control learner & Set & Observed $R^2$ & Null $q_{95}$ & perm.\ $p$ & Uninformative & Bootstrap CI (exploded) \\\\
\midrule
%s
\bottomrule
\end{tabular}}
\end{table}
""" % "\n".join(lines)
    (out / "tab_controls.tex").write_text(tex)
    return rows


def result_macros(conf, info: dict, ctrl: list[dict], out: Path) -> None:
    """Numbers the Experiments text quotes, so no value is typed by hand."""
    m = {}
    if conf is not None and len(conf):
        c = conf.copy()
        for k in ("d_r2_mean", "d_r2_ci_low", "d_r2_ci_high", "d_r2_p", "d_r2_q_bh"):
            c[k] = c[k].astype(float)
        best = c.sort_values("d_r2_mean", ascending=False).iloc[0]
        m["confNTargets"] = len(c)
        m["confNInformative"] = int(sum(_flag(x) for x in c.get("informative_bh", [])))
        m["confNAboveThreshold"] = int((c["d_r2_mean"] >= float(c["practical_threshold"].iloc[0])).sum())
        m["confNCIexcludesZero"] = int((c["d_r2_ci_low"] > 0).sum())
        m["confBestTarget"] = TARGET.get(best["target"], best["target"])
        m["confBestDelta"] = f"{best['d_r2_mean']:.2f}"
        m["confBestCI"] = f"[{best['d_r2_ci_low']:.2f}, {best['d_r2_ci_high']:.2f}]"
        m["confBestQ"] = _p(best["d_r2_q_bh"]).replace("$", "")
        m["confMinDelta"] = f"{c['d_r2_mean'].min():.2f}"
        m["confMaxDelta"] = f"{c['d_r2_mean'].max():.2f}"
        for _, r in c.iterrows():
            key = "".join(ch for ch in r["target"].title() if ch.isalpha())  # TeX names: letters only
            m[f"dR{key}"] = f"{r['d_r2_mean']:+.2f}"
            m[f"ci{key}"] = f"[{r['d_r2_ci_low']:+.2f}, {r['d_r2_ci_high']:+.2f}]"
            m[f"q{key}"] = _p(r["d_r2_q_bh"]).replace("$", "")
    if info:
        comp_beats_ti = sum(1 for (t, s), (p, i) in info.items() if s == "composition" and (t, "TI") in info and p > info[(t, "TI")][0])
        m["ladderNCompositionAboveTI"] = comp_beats_ti
        m["ladderNTargets"] = len({t for t, _ in info})
        gains = [info[(t, "TI_composition")][1] - info[(t, "composition")][1] for t, s in info if s == "composition" and (t, "TI_composition") in info]
        if gains:
            m["ladderMaxTIcompGainInDomain"] = f"{max(gains):+.2f}"
            m["ladderMinTIcompGainInDomain"] = f"{min(gains):+.2f}"
    if ctrl:
        first = ctrl[0]["run"]
        ti = [r for r in ctrl if r["run"] == first and r["set"] == "TI"]
        m["ctrlLearner"] = ti[0]["learner"] if ti else "?"
        m["ctrlNUninformative"] = sum(r["uninformative"] for r in ti)
        m["ctrlMinExploded"] = min((r["boot_exploded"] for r in ti), default=0)
        m["ctrlMaxExploded"] = max((r["boot_exploded"] for r in ti), default=0)
        m["ctrlBoot"] = ti[0]["boot_n"] if ti else 0
    (out / "results_macros.tex").write_text("".join(f"\\newcommand{{\\{k}}}{{{_tex(v)}}}\n" for k, v in m.items()))


def _scaffold_stats(res: Path, target: str) -> dict:
    """Scaffold-group counts per target (the plan asks for the number of groups and the largest
    group's share), recomputed with the pipeline's own grouping (evaluate.scaffold_groups on the
    standardised SMILES, connectivity groups merged) on the molecules that have the target."""
    try:
        import sys
        sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
        from rdkit import Chem
        from topoqspr import evaluate as ev
    except Exception:  # noqa: BLE001 - optional (RDKit)
        return {}
    mols_tab = _read(res / "molecules.csv")
    tg = _read(res / "targets.csv")
    ok = tg[target].notna() if target in tg else pd.Series(False, index=tg.index)
    ids = set(tg.loc[ok, "id"])
    sub = mols_tab[mols_tab["id"].isin(ids) & mols_tab["smiles"].notna()]
    mols = [Chem.MolFromSmiles(x) for x in sub["smiles"]]
    if not mols or any(m is None for m in mols):
        return {}
    scaf = ev.scaffold_groups(mols)
    conn = [g if isinstance(g, str) and g else i for g, i in zip(sub["connectivity_group"], sub["id"])]
    pos = {i: k for k, i in enumerate(sub["id"])}
    groups = pd.Series([scaf[pos[g]] if g in pos else scaf[k] for k, g in enumerate(conn)])
    counts = groups.value_counts()
    return dict(n=int(len(groups)), groups=int(len(counts)), largest=int(counts.iloc[0]),
                largest_share=float(counts.iloc[0] / len(groups)),
                singletons=int((counts == 1).sum()))


def scaffold_table(res: Path, learner: str, out: Path) -> dict:
    """Ladder under scaffold-grouped outer folds, with the paired TI - size gain per target."""
    summary = _read(res / "summary.csv")
    ad = _read(res / "ad_summary.csv") if (res / "ad_summary.csv").exists() else None
    targets = list(dict.fromkeys(summary["target"]))
    sets = [x for x in LADDER if x in set(summary["set"])]
    head = " & ".join(["Feature set"] + [f"\\multicolumn{{2}}{{c}}{{{TARGET.get(t, _tex(t))}}}" for t in targets]) + " \\\\"
    sub = " & ".join([""] + ["all & in-dom."] * len(targets)) + " \\\\"
    lines, macros = [], {}
    for x in sets:
        cells = []
        for t in targets:
            r = summary[(summary["target"] == t) & (summary["learner"] == learner) & (summary["set"] == x)]
            a = ad[(ad["target"] == t) & (ad["learner"] == learner) & (ad["set"] == x)] if ad is not None else pd.DataFrame()
            if r.empty:
                cells += ["--", "--"]
                continue
            indom = float(a.iloc[0]["r2_in_domain_pooled_mean"]) if len(a) and pd.notna(a.iloc[0]["r2_in_domain_pooled_mean"]) else math.nan
            cells += [_r2cell(r.iloc[0]["r2_pooled_mean"]), _r2cell(indom)]
        lines.append(" & ".join([LABEL.get(x, _tex(x))] + cells) + " \\\\")
    drow, grow = ["$\\Delta R^2$ (TI $-$ size)"], ["scaffold groups"]
    for t in targets:
        r = summary[(summary["target"] == t) & (summary["learner"] == learner) & (summary["set"] == "TI")]
        if r.empty or pd.isna(r.iloc[0]["d_r2_mean"]):
            drow.append("\\multicolumn{2}{c}{--}")
        else:
            d, lo, hi, pv = (float(r.iloc[0][k]) for k in ("d_r2_mean", "d_r2_ci_low", "d_r2_ci_high", "d_r2_p"))
            ptxt = _p(pv).replace("$", "")
            drow.append(f"\\multicolumn{{2}}{{c}}{{{d:+.2f} [{lo:+.2f}, {hi:+.2f}], $p{'' if ptxt.startswith('<') else '='}{ptxt}$}}")
            key = "".join(ch for ch in t.title() if ch.isalpha())
            macros[f"scafdR{key}"] = f"{d:+.2f}"
            macros[f"scafci{key}"] = f"[{lo:+.2f}, {hi:+.2f}]"
            macros[f"scafp{key}"] = _p(pv).replace("$", "")
            macros.setdefault("scafNCIexcludesZero", 0)
            macros["scafNCIexcludesZero"] += int(lo > 0)
        st = _scaffold_stats(res, t)
        grow.append(f"\\multicolumn{{2}}{{c}}{{{st['groups']} (largest {100 * st['largest_share']:.1f}\\%)}}" if st else "\\multicolumn{2}{c}{--}")
        if st:
            macros[f"scafGroups{key}"] = st["groups"]
            macros[f"scafLargestShare{key}"] = f"{100 * st['largest_share']:.1f}"
    macros["scafNTargets"] = len(targets)
    tex = r"""\begin{table}[t]
\centering\footnotesize
\caption{Baseline ladder under scaffold-grouped outer folds: Bemis--Murcko scaffolds, acyclic molecules as singletons, stereoisomers merged into their scaffold's group; learner \texttt{selected}; $5\times5$ repeated nested CV; frozen configuration \texttt{studies/main\_scaffold.json}. Pooled $R^2$ on all molecules and inside the applicability domain; the last rows give the paired gain of the topological indices over the size baseline on identical scaffold folds with the corrected repeated $k$-fold $t$ interval, and the number of scaffold groups with the largest group's share of the molecules. Generated by \texttt{tools/make\_results.py}.}
\label{tab:ladderScaffold}
\resizebox{\linewidth}{!}{%%
\begin{tabular}{l%s}
\toprule
%s
%s
\midrule
%s
\midrule
%s
%s
\bottomrule
\end{tabular}}
\end{table}
""" % ("rr" * len(targets), head, sub, "\n".join(lines), " & ".join(drow) + " \\\\", " & ".join(grow) + " \\\\")
    (out / "tab_ladder_scaffold.tex").write_text(tex)
    (out / "scaffold_macros.tex").write_text("".join(f"\\newcommand{{\\{k}}}{{{_tex(v)}}}\n" for k, v in macros.items()))
    return macros


def provenance(rec: dict, out: Path) -> None:
    code = rec.get("code") or {}
    ch = rec.get("chembl") or {}
    cfg = rec.get("config") or {}
    ev = cfg.get("evaluation") or {}
    pr = cfg.get("protocol") or {}
    macros = {
        "runCommit": str(code.get("commit", "?"))[:12] + (" (modified)" if code.get("dirty") else ""),
        "topoqsprVersion": rec.get("topoqspr_version", "?"),
        "chemblRelease": ch.get("release", "n/a") if ch else "n/a",
        "configHash": str(rec.get("config_sha256") or cfg.get("config_sha256") or "?")[:12],
        "outerSplits": ev.get("outer_splits", "?"),
        "outerRepeats": len(ev.get("seeds", []) or []),
        "innerSplits": ev.get("inner_splits", "?"),
        "nPermutations": ((pr.get("permutation") or {}).get("n_permutations", "?")),
        "nBoot": ((pr.get("bootstrap") or {}).get("n_boot", "?")),
        "nMolecules": ((rec.get("counts") or {}).get("standardised", "?")),
    }
    (out / "provenance.tex").write_text(
        "".join(f"\\newcommand{{\\{k}}}{{{_tex(v)}}}\n" for k, v in macros.items()))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("results")
    ap.add_argument("out")
    ap.add_argument("--learner", default="selected")
    ap.add_argument("--scaffold-run", default=None, help="results dir of the scaffold-split run (tab_ladder_scaffold.tex)")
    ap.add_argument("--extra-controls", nargs="*", default=[],
                    help="further run dirs whose protocol stage (permutation/bootstrap) is added to the controls table")
    a = ap.parse_args()
    res, out = Path(a.results), Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    summary = _read(res / "summary.csv")
    ad = _read(res / "ad_summary.csv") if (res / "ad_summary.csv").exists() else None
    info = ladder_table(summary, ad, a.learner, out)
    conf = None
    if (res / "confirmatory.csv").exists():
        conf = _read(res / "confirmatory.csv")
        confirmatory_table(conf, out)
        forest(conf, out)
    ctrl = controls_table(res, [Path(x) for x in a.extra_controls], out)
    provenance(json.loads((res / "run_record.json").read_text()), out)
    result_macros(conf, info, ctrl, out)
    if a.scaffold_run:
        print(scaffold_table(Path(a.scaffold_run), a.learner, out))
    print("results written to", out)


if __name__ == "__main__":
    main()
