"""Paper results: LaTeX tables and figures generated only from a run's result files.

Usage: python tools/make_results.py RESULTS_DIR OUT_DIR

Reads (written by `topoqspr run` with a protocol stage):
  confirmatory.csv        one row per (target x comparison) of the confirmatory family
  summary.csv             baseline ladder per target / feature set / learner
  run_record.json         provenance (commit, release, config hash, seeds)

Writes:
  tab_confirmatory.tex    the confirmatory table (ΔR², CI, BH/BY q, permutation p, bootstrap CI)
  tab_ladder.tex          pooled R² for every feature set x target (learner "selected")
  fig_confirmatory.pdf/png forest plot of ΔR²(TI − size) with corrected-t and bootstrap intervals
  provenance.tex          one macro per provenance fact (\\runCommit, \\chemblRelease, ...)
No value in these files is typed by hand; the paper \\input{}s them.
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402

SERIES = "#2a78d6"   # reference palette slot 1 (validated)
INK, INK_2, GRID = "#0b0b0b", "#52514e", "#d9d8d4"
LADDER = ["null", "size", "size_rings", "composition", "TI", "TI_composition", "rdkit2d"]
LABEL = {"null": "null (mean)", "size": "size", "size_rings": "size + rings", "composition": "composition",
         "TI": "topological indices", "TI_composition": "indices + composition", "rdkit2d": "RDKit 2D"}
TARGET = {"mp_bradley": "melting point (Bradley)", "mp_opera": "melting point (OPERA)",
          "logp_opera": "log P (OPERA)", "logd74_az": "log D$_{7.4}$ (AstraZeneca)",
          "logs_aqsoldb": "log S (AqSolDB)", "logs_opera": "log S (OPERA)",
          "logs74_az": "log S pH 7.4 (AstraZeneca)", "logs68_biogen": "log S pH 6.8 (Biogen)"}

plt.rcParams.update({"font.size": 8, "axes.edgecolor": INK_2, "axes.labelcolor": INK, "xtick.color": INK_2,
                     "ytick.color": INK_2, "axes.spines.top": False, "axes.spines.right": False,
                     "figure.dpi": 150, "savefig.bbox": "tight"})


def _read(path: Path) -> pd.DataFrame:
    # "null" is a feature-set name, not a missing value
    return pd.read_csv(path, keep_default_na=False, na_values=[""])


def _f(x, nd=2, dash="--") -> str:
    try:
        v = float(x)
    except (TypeError, ValueError):
        return dash
    return dash if not math.isfinite(v) else f"{v:.{nd}f}"


def _p(x) -> str:
    try:
        v = float(x)
    except (TypeError, ValueError):
        return "--"
    if not math.isfinite(v):
        return "--"
    return "$<$0.001" if v < 0.001 else f"{v:.3f}"


def _flag(x) -> bool:
    return str(x).strip().lower() in ("true", "1")


def _tex(s: str) -> str:
    return str(s).replace("_", "\\_").replace("%", "\\%")


def confirmatory_table(conf: pd.DataFrame, out: Path) -> None:
    rows = []
    for _, r in conf.iterrows():
        in_fam = _flag(r.get("in_family", True))
        rows.append(" & ".join([
            TARGET.get(r["target"], _tex(r["target"])), _tex(r["comparison"]), _f(r["n"], 0),
            _f(r["d_r2_mean"], 3), f"[{_f(r['d_r2_ci_low'], 3)}, {_f(r['d_r2_ci_high'], 3)}]",
            _p(r["d_r2_p"]), _p(r["d_r2_q_bh"]) if in_fam else "excl.", _p(r["d_r2_q_by"]) if in_fam else "excl.",
            _p(r.get("perm_p_set")), _f(r["d_mae_mean"], 3),
            f"[{_f(r.get('boot_d_r2_ci_low'), 3)}, {_f(r.get('boot_d_r2_ci_high'), 3)}]",
            ("yes" if _flag(r.get("informative_bh")) else "no") if in_fam else "excl.",
        ]) + " \\\\")
    fam_m = int(float(conf["family_m"].iloc[0])) if "family_m" in conf and len(conf) else len(conf)
    thr = float(conf["practical_threshold"].iloc[0]) if len(conf) else 0.05
    tex = r"""\begin{table}[t]
\centering\footnotesize
\caption{Confirmatory family (%d members): paired gain of the topological-index model over the size baseline, learner \texttt{selected}. $\Delta R^2$ and $\Delta$MAE are means over %s repeated outer folds with the corrected repeated $k$-fold $t$-test 95\%% CI and $p$; $q$: Benjamini--Hochberg and Benjamini--Yekutieli over the family; perm.\ $p$: Y-randomised control; boot.\ CI: percentile interval from the whole-procedure paired bootstrap. ``Informative'': $q_{\mathrm{BH}}\le0.05$ and $\Delta R^2>0$; practical threshold $\Delta R^2\ge%.2f$. Generated by \texttt{tools/make\_results.py}.}
\label{tab:confirmatory}
\resizebox{\linewidth}{!}{%%
\begin{tabular}{llrrlllllrll}
\toprule
Target & Comparison & $n$ & $\Delta R^2$ & 95\%% CI & $p$ & $q_{\mathrm{BH}}$ & $q_{\mathrm{BY}}$ & perm.\ $p$ & $\Delta$MAE & boot.\ CI & Informative \\
\midrule
%s
\bottomrule
\end{tabular}}
\end{table}
""" % (fam_m, "the", thr, "\n".join(rows))
    (out / "tab_confirmatory.tex").write_text(tex)


def ladder_table(summary: pd.DataFrame, learner: str, out: Path) -> None:
    targets = list(dict.fromkeys(summary["target"]))
    sets = [s for s in LADDER if s in set(summary["set"])]
    head = " & ".join(["Feature set"] + [TARGET.get(t, _tex(t)) for t in targets]) + " \\\\"
    lines = []
    for s in sets:
        cells = []
        for t in targets:
            r = summary[(summary["target"] == t) & (summary["learner"] == learner) & (summary["set"] == s)]
            if r.empty:
                cells.append("--")
            else:
                v = _f(r.iloc[0]["r2_pooled_mean"], 3)
                cells.append(v + ("$^{\\dagger}$" if _flag(r.iloc[0]["underpowered"]) else ""))
        lines.append(" & ".join([LABEL.get(s, _tex(s))] + cells) + " \\\\")
    ns = " & ".join(["$n$"] + [_f(summary[summary["target"] == t]["n"].iloc[0], 0) for t in targets]) + " \\\\"
    tex = r"""\begin{table}[t]
\centering\footnotesize
\caption{Baseline ladder: pooled cross-validated $R^2$ of each feature set (learner \texttt{selected}, chosen inside each outer training fold; repeated nested CV). $^{\dagger}$underpowered. Generated by \texttt{tools/make\_results.py}.}
\label{tab:ladder}
\begin{tabular}{l%s}
\toprule
%s
\midrule
%s
\midrule
%s
\bottomrule
\end{tabular}
\end{table}
""" % ("r" * len(targets), head, "\n".join(lines), ns)
    (out / "tab_ladder.tex").write_text(tex)


def forest(conf: pd.DataFrame, out: Path) -> None:
    rows = list(conf.iterrows())
    fig, ax = plt.subplots(figsize=(4.8, 0.45 * max(len(rows), 2) + 1.1))
    ax.set_ylim(-0.6, len(rows) - 0.4)
    thr = float(conf["practical_threshold"].iloc[0]) if len(rows) else 0.05
    for i, (_, r) in enumerate(rows[::-1]):
        m, lo, hi = (float(r[k]) if pd.notna(r[k]) else math.nan for k in ("d_r2_mean", "d_r2_ci_low", "d_r2_ci_high"))
        blo, bhi = (float(r[k]) if ("boot_d_r2_ci_low" in r and pd.notna(r[k])) else math.nan
                    for k in ("boot_d_r2_ci_low", "boot_d_r2_ci_high"))
        hollow = _flag(r.get("underpowered")) or not _flag(r.get("in_family", True))
        if math.isfinite(lo) and math.isfinite(hi):
            ax.plot([lo, hi], [i + 0.12, i + 0.12], color=SERIES, lw=2, solid_capstyle="round", zorder=2)
        if math.isfinite(blo) and math.isfinite(bhi):
            ax.plot([blo, bhi], [i - 0.12, i - 0.12], color=INK_2, lw=1.2, solid_capstyle="round", zorder=2)
        if math.isfinite(m):
            ax.scatter([m], [i + 0.12], s=30, zorder=4, color="white" if hollow else SERIES,
                       edgecolors=SERIES, linewidths=1.5)
    ax.set_yticks(range(len(rows)), [f"{TARGET.get(r['target'], r['target']).replace('$', '')}: {r['comparison']}"
                                      for _, r in rows[::-1]])
    ax.axvline(0, color=INK_2, lw=0.8)
    ax.axvline(thr, color=INK_2, lw=0.8, ls=(0, (3, 3)))
    ax.text(thr, len(rows) - 0.45, f" {thr:+.2f} practical threshold", fontsize=6.5, color=INK_2, va="bottom")
    ax.set_xlabel("ΔR² of topological indices over the size baseline")
    ax.grid(axis="x", color=GRID, lw=0.5)
    fig.text(0, -0.08, "Blue: corrected repeated k-fold t 95 % CI (upper bar). Grey: whole-procedure\n"
             "paired bootstrap 95 % CI (lower bar). Hollow: underpowered or outside the family.",
             fontsize=6.5, color=INK_2, va="top")
    for ext in ("pdf", "png"):
        fig.savefig(out / f"fig_confirmatory.{ext}")
    plt.close(fig)


def provenance(rec: dict, out: Path) -> None:
    code = rec.get("code") or {}
    ch = rec.get("chembl") or {}
    cfg = rec.get("config") or {}
    ev = cfg.get("evaluation") or {}
    pr = cfg.get("protocol") or {}
    macros = {
        "runCommit": str(code.get("commit", "?"))[:12] + (" (modified)" if code.get("dirty") else ""),
        "topoqsprVersion": rec.get("topoqspr_version", "?"),
        "chemblRelease": ch.get("release", "n/a") if ch else "n/a",
        "configHash": str(rec.get("config_sha256") or cfg.get("config_sha256") or "?")[:12],
        "outerSplits": ev.get("outer_splits", "?"),
        "outerRepeats": len(ev.get("seeds", []) or []),
        "innerSplits": ev.get("inner_splits", "?"),
        "nPermutations": ((pr.get("permutation") or {}).get("n_permutations", "?")),
        "nBoot": ((pr.get("bootstrap") or {}).get("n_boot", "?")),
        "nMolecules": ((rec.get("counts") or {}).get("standardised", "?")),
    }
    (out / "provenance.tex").write_text(
        "".join(f"\\newcommand{{\\{k}}}{{{_tex(v)}}}\n" for k, v in macros.items()))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("results")
    ap.add_argument("out")
    ap.add_argument("--learner", default="selected")
    a = ap.parse_args()
    res, out = Path(a.results), Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    summary = _read(res / "summary.csv")
    ladder_table(summary, a.learner, out)
    if (res / "confirmatory.csv").exists():
        conf = _read(res / "confirmatory.csv")
        confirmatory_table(conf, out)
        forest(conf, out)
    provenance(json.loads((res / "run_record.json").read_text()), out)
    print("results written to", out)


if __name__ == "__main__":
    main()
