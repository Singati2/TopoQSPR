"""Supplementary Table S1: every index of the registry with its formula, primary source and the
tests that verify it (from docs/INDEX_VERIFICATION.md), plus the list of entropies.

Usage: python tools/make_supplement.py OUT_DIR

Writes supp_S1_indices.tex (a longtable; the supplement \\input{}s it) and supp_S1_macros.tex.
Nothing is typed by hand: names, families, formulas and reference keys come from
``topoqspr.indices.REGISTRY``; the test names come from the verification document.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from topoqspr.entropy import ENTROPY_NAMES  # noqa: E402
from topoqspr.indices import REGISTRY  # noqa: E402

FAMILY = {"degree": "deg.", "reverse_degree": "rev.\\ deg.", "neighbourhood_degree_sum": "nbhd.\\ sum",
          "distance": "dist.", "matching": "match.", "entropy": "entr."}


def _tex(s: str) -> str:
    return str(s).replace("_", "\\_").replace("%", "\\%").replace("&", "\\&")


def verification_tests(md: Path) -> dict[str, tuple[str, str]]:
    """{index name: (test names, status)} from the markdown index table (names in back-ticks;
    one row may list several names)."""
    out = {}
    rk_common = "test_rk_indices_use_the_published_weight_tables, test_rk_beyond_delta_is_nan_with_reason"
    for line in md.read_text(encoding="utf-8").splitlines():
        if not line.startswith("| `"):
            continue
        # cells are separated by unescaped pipes (formulas use \| for absolute values)
        cells = [c.strip() for c in re.split(r"(?<!\\)\|", line.strip().strip("|"))]
        names = re.findall(r"`([^`]+)`", cells[0])
        if len(cells) >= 6:            # main table: Index, Definition, Source, Code, Tests, Status
            tests, status = ", ".join(re.findall(r"`([^`]+)`", cells[4])), cells[5]
        elif len(cells) == 5:          # reverse-degree table: Index, phi, Source, Further tests, Status
            extra = ", ".join(re.findall(r"`([^`]+)`", cells[3]))
            tests, status = rk_common + (", " + extra if extra else ""), cells[4]
        else:
            continue
        for n in names:
            out.setdefault(n, (tests, status))
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("out")
    a = ap.parse_args()
    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    tests = verification_tests(ROOT / "docs" / "INDEX_VERIFICATION.md")
    specs = list(REGISTRY.values()) if hasattr(REGISTRY, "values") else list(REGISTRY)
    rows, missing = [], []
    for s in specs:
        t, status = tests.get(s.name, ("", ""))
        if not t:
            missing.append(s.name)
        rows.append(" & ".join([
            f"\\texttt{{{_tex(s.name)}}}", FAMILY.get(s.family, _tex(s.family)),
            f"${s.latex}$" if len(s.latex) <= 80 else f"\\scalebox{{0.72}}{{${s.latex}$}}",  # long R_k forms
            f"\\cite{{{s.ref}}}", ("\\tiny " + _tex(t).replace("\\_", "\\_\\allowbreak{}")) if t else "--",
        ]) + " \\\\")
    tex = r"""\scriptsize
\setlength\LTleft{0pt}\setlength\LTright{0pt}
\begin{longtable}{@{}p{1.5cm}p{0.95cm}p{4.1cm}p{0.8cm}p{4.3cm}@{}}
\caption{Supplementary Table S1. Every topological index of \ml{}~v1.0: registry name, family (deg.: degree; rev.\ deg.: reverse degree $c_u=\Delta-d_u+1$ and its generalisation $R_k$; nbhd.\ sum: neighbourhood degree sum $S_u$; dist.: distance; match.: matching; entr.: entropy), definition as implemented, primary source, and the unit tests that verify it (\texttt{tests/test\_indices.py}: closed forms on paths, cycles, stars and complete graphs, algebraic identities, brute-force enumeration, Mordred, ChemGraphX and printed literature values). All \suppNIndices{} indices have status \emph{verified} in \texttt{docs/INDEX\_VERIFICATION.md}. Generated by \texttt{tools/make\_supplement.py}.}
\label{tab:S1} \\
\toprule
Index & Family & Definition & Source & Verified by \\
\midrule
\endfirsthead
\toprule
Index & Family & Definition & Source & Verified by \\
\midrule
\endhead
\bottomrule
\endfoot
%s
\end{longtable}
""" % "\n".join(rows)
    (out / "supp_S1_indices.tex").write_text(tex)
    ents = ", ".join(f"\\texttt{{{_tex(e)}}}" for e in ENTROPY_NAMES)
    (out / "supp_S1_macros.tex").write_text(
        f"\\newcommand{{\\suppNIndices}}{{{len(specs)}}}\n\\newcommand{{\\suppNEntropies}}{{{len(ENTROPY_NAMES)}}}\n"
        f"\\newcommand{{\\suppNVerified}}{{{sum(1 for s in specs if tests.get(s.name, ('', ''))[1] == 'verified')}}}\n"
        f"\\newcommand{{\\suppEntropyList}}{{{ents}}}\n")
    # the supplement cites index sources from docs/index_refs.bib; entries already in paper/refs.bib
    # are left out so bibtex sees each key once
    main_keys = set(re.findall(r"@\w+\{([^,]+),", (ROOT / "paper" / "refs.bib").read_text(encoding="utf-8")))
    extra, keep = [], False
    for block in re.split(r"(?=^@)", (ROOT / "docs" / "index_refs.bib").read_text(encoding="utf-8"), flags=re.M):
        m = re.match(r"@\w+\{([^,]+),", block)
        if m and m.group(1) not in main_keys:
            extra.append(block.rstrip() + "\n")
    (out / "index_refs_extra.bib").write_text("\n".join(extra))
    print(f"{len(specs)} indices, {len(ENTROPY_NAMES)} entropies; without a verification row: {missing}; "
          f"{len(extra)} index references not in refs.bib written to index_refs_extra.bib")


if __name__ == "__main__":
    main()
